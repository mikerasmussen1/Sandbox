export interface MapDef {
  biome: Biome;
  sun: Vec;
  plaza: number;
  routes: Route[];
  flights: Route[];
  pads: Vec[];
}

function build(biome: Biome, sun: Vec, plaza: number, routes: Route[], pads: readonly Vec[]): MapDef {
  return {
    biome,
    sun,
    plaza,
    routes,
    flights: routes.map((route) => flightOf(route, sun)),
    pads: pads.slice(),
  };
}

